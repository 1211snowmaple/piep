import { cleanup, fireEvent, render, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { SearchField } from "./SearchField";
const search = vi.hoisted(() => vi.fn());
vi.mock("./pcApi", () => ({ searchPcSuggestions: search }));
afterEach(cleanup);
it("候補を表示し、キーボードで選べ、通常の Enter は検索できる", async () => {
  const item = { kind: "author", label: "試験作者", value: "試験作者", count: 2 };
  const last = { kind: "tag", label: "試験タグ", value: "試験タグ", count: 1 };
  search.mockResolvedValue([item, last]);
  const onSuggestion = vi.fn();
  const onSubmit = vi.fn();
  const view = render(<SearchField value="試験" placeholder="検索" label="作品を検索" onChange={() => {}} onSubmit={onSubmit} onSuggestion={onSuggestion} />);
  const input = view.getByRole("combobox");
  fireEvent.focus(input);
  await waitFor(() => expect(view.getAllByRole("option")).toHaveLength(2));
  fireEvent.submit(input.closest("form")!);
  expect(onSubmit).toHaveBeenCalledWith("試験");
  fireEvent.focus(input);
  await waitFor(() => expect(view.getAllByRole("option")).toHaveLength(2));
  fireEvent.keyDown(input, { key: "ArrowDown" });
  fireEvent.submit(input.closest("form")!);
  expect(onSuggestion).toHaveBeenCalledWith(item);
  fireEvent.focus(input);
  await waitFor(() => expect(view.getAllByRole("option")).toHaveLength(2));
  fireEvent.keyDown(input, { key: "ArrowUp" });
  fireEvent.submit(input.closest("form")!);
  expect(onSuggestion).toHaveBeenLastCalledWith(last);
});
it("古い応答が後から届いても今の候補へ混ぜず、日本語の変換中は検索しない", async () => {
  let finish!: (items: unknown[]) => void;
  search.mockReturnValueOnce(new Promise((resolve) => { finish = resolve; })).mockResolvedValue([]);
  const onSubmit = vi.fn();
  const props = { placeholder: "検索", label: "作品を検索", onChange: () => {}, onSubmit, onSuggestion: () => {} };
  const view = render(<SearchField {...props} value="古い" />);
  const input = view.getByRole("combobox");
  fireEvent.focus(input);
  await waitFor(() => expect(finish).toBeDefined());
  view.rerender(<SearchField {...props} value="新しい" />);
  finish([{ kind: "tag", label: "古い候補", value: "古い候補", count: 1 }]);
  await waitFor(() => expect(view.queryByRole("option")).toBeNull());
  fireEvent.compositionStart(input);
  fireEvent.submit(input.closest("form")!);
  expect(onSubmit).not.toHaveBeenCalled();
});
