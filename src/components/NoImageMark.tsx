/**
 * 画像が無いことを、画像の形で示す。
 *
 * pixiv も FANBOX も、プロフィール画像を置いていない人には一枚の絵を出す。
 * 保存元でそう見えていたものが、こちら側では人型の線画に化けていた。線画は
 * 「まだ読み込んでいない」「そういう項目が無い」にも見えるので、「絵はあるはず
 * だが、この人は置いていない」という一番多い状況が伝わらない。
 *
 * pixiv が返す no_profile を保存済みの作者はすでにこの絵で表示されていた。
 * FANBOX は画像が無いと URL 自体を返さないので、保存するものが無く、そこだけ
 * 別の見た目になっていた。同じ絵を同梱して、保存元での見え方に揃える。
 *
 * プロフィール画像という概念を持たない保存元には使わない。無いものを「無い画像」
 * として見せても嘘になるので、そちらは人型やシリーズの記号のままにする。
 */
export function NoImageMark({ label = "画像なし" }: { label?: string }) {
  // 遅延読み込みはしない。1.7KB を全カードで使い回す一枚なので、待たせる意味が
  // なく、待たせると画像の場所が一瞬空白になる。
  return <img className="no-image-mark" src="/no-profile.png" alt={label} decoding="async" />;
}
