//! 添付 PDF から本文を取り出す。
//!
//! FANBOX では、規制を避けるために本文そのものを PDF で添付する作者がいる。
//! 投稿本文には挨拶しか無く、作品は添付の中にある。取り出さない限り、その
//! 作品は棚にあっても読めず、検索にも出てこない。
//!
//! # 二つの経路
//!
//! **タグ付き PDF なら構造ツリーを読む。** Word も Google ドキュメントも
//! `/StructTreeRoot` を書き出しており、`/P` 要素が段落そのものになっている。
//! 作者が切れ目を書き残しているのだから、こちらで推測する理由がない。
//! ヘッダー・フッター・ページ番号は `/Artifact` なので、除外の規則を書かなくても
//! 落ちる。
//!
//! **タグが無ければ行の形から組み直す。** 右端まで届いている行は折り返し、
//! 届いていない行は段落の終わり、行送りが開けば空行。棚の実物（すべてタグ付き）
//! で構造ツリーの結果を正解として測ると、段落の一致率は 92〜99% だった。
//! 完全ではないので、こちらを使ったときは呼び出し側へそう伝える。
//!
//! # 落とさないことを毎ページ確かめる
//!
//! 構造ツリーは、要素に属さない文字を取りこぼしうる。そこで**ページごとに、
//! pdfium が返す全文字数と、経路が拾った文字数を突き合わせる。** 合わなければ
//! そのページだけ行から組み直す。黙って本文が欠けるより、段落の精度を落とす。

